/**
 * Catálogo CURADO de ejercicios: la información revisada a mano que el dataset free-exercise-db no
 * trae (patrón de movimiento, porciones musculares, errores, precauciones, variantes y rango de
 * repeticiones orientativo).
 *
 * Reglas de este archivo:
 *  - Solo ejercicios reales y de uso común. Los músculos son los descritos en anatomía funcional
 *    estándar; cuando no hay certeza sobre una porción se usa el músculo completo.
 *  - Lo que NO aparece aquí queda en la base como `pendiente_revision`: conserva los datos gruesos
 *    del dataset y un patrón deducido por el nombre, pero nunca se presenta como verificado.
 *  - `create` marca ejercicios que el dataset no trae (id con prefijo DV_). No tienen imágenes.
 *
 * De este archivo se genera supabase/migrations/014_catalog_seed.sql (scripts/build-catalog-sql.mjs).
 * Archivo autocontenido a propósito: Node lo importa directamente para generar el SQL.
 */

export interface CuratedExercise {
  id: string;
  /** Patrón de movimiento (código de MOVEMENT_PATTERNS). */
  pattern: string;
  /** Músculos principales, el motor primario primero (códigos de MUSCLES). */
  principal: string[];
  secundarios: string[];
  /** Función muscular: qué acción articular entrena. */
  funcion: string;
  errores: string[];
  precauciones: string[];
  seguridad: string[];
  variantes: string[];
  /** Rango de repeticiones orientativo. */
  reps: [number, number];
  /** Equipo exigido (claves de GEAR_OPTIONS) cuando la regla general del dataset no alcanza. */
  gear?: string[];
  create?: {
    name: string;
    nameEs: string;
    equipment: string;
    mechanic: 'compound' | 'isolation';
    level: 'beginner' | 'intermediate' | 'expert';
    force: 'push' | 'pull' | 'static';
    instructionsEs: string[];
  };
}

